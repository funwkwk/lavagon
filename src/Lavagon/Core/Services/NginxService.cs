using System.Diagnostics;
using System.IO;

namespace Lavagon.Core.Services
{
    /// <summary>Nginx + php-cgi (FastCGI) - works with both TS and NTS PHP builds.</summary>
    public class NginxService : ServiceBase
    {
        public override string Key => "nginx";
        public override string Title => "Nginx";
        protected override string[] ExeCandidates => new[] { "nginx.exe" };

        public int HttpPort => Port("Port", 80);
        public int PhpCgiPort => Port("PhpCgiPort", 9123);
        public override int[] Ports => new[] { HttpPort };
        public override string ActionLabel => "Reload";
        public override void Action() => Restart();

        public string EtcDir => Path.Combine(AppPaths.Etc, "nginx");
        public string ConfFile => Path.Combine(EtcDir, "nginx.conf");
        public string SitesDir => Path.Combine(EtcDir, "sites-enabled");
        public string CustomConf => Path.Combine(EtcDir, "custom.conf");
        private string Prefix => Path.Combine(AppPaths.Tmp, "nginx");
        private string PhpPidFile => Path.Combine(AppPaths.PidDir, "php-cgi.pid");

        protected override void Prepare()
        {
            if (!Php.Installed)
                throw new LavagonException("PHP is not installed.\n\nExtract PHP into:\n" + Path.Combine(AppPaths.Bin, "php") + "\\<version>");
            Php.CheckRuntime();
            Php.EnsureIni();

            foreach (var d in new[] { SitesDir, Path.Combine(Prefix, "logs"), Path.Combine(Prefix, "temp") })
                Directory.CreateDirectory(d);
            if (!File.Exists(CustomConf))
                File.WriteAllText(CustomConf, "# Your own http{} level Nginx directives. Lavagon never overwrites this file.\r\n");

            VirtualHosts.SyncNginx();
            WriteIfChanged(ConfFile, NginxConf());

            var test = Proc.Run(ExePath, $"-t -p \"{AppPaths.Fwd(Prefix)}/\" -c \"{AppPaths.Fwd(ConfFile)}\"", Dir, 30000);
            if (!test.Ok) throw new LavagonException("Nginx configuration error:\n\n" + test.Output);

            StartPhpCgi();
        }

        protected override Process Launch() =>
            Proc.StartHidden(ExePath, $"-p \"{AppPaths.Fwd(Prefix)}/\" -c \"{AppPaths.Fwd(ConfFile)}\"", Dir);

        protected override string StartFailureDetails() => Tail(Path.Combine(AppPaths.Logs, "nginx_error.log"));

        public override void Stop()
        {
            base.Stop();
            StopPhpCgi();
        }

        private void StartPhpCgi()
        {
            StopPhpCgi();
            if (!File.Exists(Php.PhpCgiExe)) throw new LavagonException("php-cgi.exe was not found in " + Php.Dir);
            if (Net.IsListening(PhpCgiPort))
                throw new LavagonException($"Port {PhpCgiPort} (php-cgi for Nginx) is already in use.");
            var env = Env.Variables();
            env["PHP_FCGI_MAX_REQUESTS"] = "0";
            var p = Proc.StartHidden(Php.PhpCgiExe, $"-b 127.0.0.1:{PhpCgiPort} -c \"{Php.IniPath}\"", Php.Dir, env);
            File.WriteAllText(PhpPidFile, p.Id.ToString());
        }

        private void StopPhpCgi()
        {
            if (!File.Exists(PhpPidFile)) return;
            int.TryParse(File.ReadAllText(PhpPidFile).Trim(), out int pid);
            if (Proc.IsAlive(pid, "php-cgi")) Proc.KillTree(pid);
            File.Delete(PhpPidFile);
        }

        private string NginxConf()
        {
            var f = AppPaths.Fwd;
            var docRoot = f(App.Settings.DocumentRoot);
            return
$@"# =============================================================================
# Generated by Lavagon on every start - DO NOT EDIT, your changes will be lost.
# Put your own directives in: {f(CustomConf)}
# =============================================================================
worker_processes  1;
error_log  ""{f(AppPaths.Logs)}/nginx_error.log"";
pid        ""{f(Prefix)}/nginx.pid"";

events {{
    worker_connections  1024;
}}

http {{
    include       ""{f(Dir)}/conf/mime.types"";
    default_type  application/octet-stream;
    access_log    ""{f(AppPaths.Logs)}/nginx_access.log"";
    sendfile      off;
    keepalive_timeout  65;
    client_max_body_size 2000M;
    server_names_hash_bucket_size 128;

    upstream php_upstream {{
        server 127.0.0.1:{PhpCgiPort} weight=1 max_fails=1 fail_timeout=1;
    }}

    server {{
        listen {HttpPort} default_server;
        server_name localhost;
        root ""{docRoot}"";
        index index.php index.html index.htm;
        autoindex on;

        location ~ \.php$ {{
            include ""{f(Dir)}/conf/fastcgi.conf"";
            fastcgi_pass php_upstream;
        }}
    }}

    include ""{f(CustomConf)}"";
    include ""{f(SitesDir)}/*.conf"";
}}
";
        }
    }
}
